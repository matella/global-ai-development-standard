"""Shared GADS install layout used by the install, uninstall, and audit scripts."""
import hashlib
import json
import re
from pathlib import Path

SOURCE = Path(__file__).resolve().parents[1]
LOCK = "gads/install.json"
# Kit directories installed under gads/; Markdown references to them are rewritten.
KIT_DIRS = {"standard": "gads/standard", "templates": "gads/templates", "agents": "gads/agents"}
ROOT_FILES = ["AGENTS.md", "CLAUDE.md"]
CLAUDE_ADAPTER = "adapters/claude-code"
# Project-owned files: created when absent, never overwritten or removed.
SEEDS = {"templates/PROJECT.md": "gads/PROJECT.md"}
# Never replaced when already present, even with --force: they hold project settings.
CREATE_ONLY = {".claude/settings.json"}
STANDARD_FILES = ["OPERATING_STANDARD.md", "SECURITY_AND_AUTONOMY.md",
                  "WORKFLOW_AND_GATES.md", "DECISION_POLICY.md"]
# Claude Code tools granted per portable access level; None inherits all tools.
CLAUDE_TOOLS = {"read-only": "Read, Grep, Glob, Bash", "read-write": None}
KIT_REF = re.compile(r"(?<=`)(standard|templates|agents)/")


def sha256(data):
    """Hash content with CRLF read as LF, so a `core.autocrlf=true` checkout still matches the lock.

    Every installed file is text and the kit is checked out with LF, so hashes of LF files are
    unchanged and existing install locks stay valid.
    """
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def version():
    return (SOURCE / "VERSION").read_text(encoding="utf-8").strip()


def rewrite_refs(text):
    return KIT_REF.sub(lambda m: f"{KIT_DIRS[m.group(1)]}/", text)


def split_frontmatter(text):
    """Return (fields, body) for a Markdown file with simple `key: value` frontmatter."""
    if not text.startswith("---\n"):
        return {}, text
    head, _, body = text[4:].partition("\n---\n")
    fields = dict(line.split(":", 1) for line in head.splitlines() if ":" in line)
    return {k.strip(): v.strip() for k, v in fields.items()}, body.lstrip("\n")


def claude_agent(src_rel, text):
    """Render a canonical role definition as a Claude Code subagent file."""
    fields, body = split_frontmatter(text)
    lines = ["---", f"name: gads-{fields['name']}", f"description: {fields['description']}"]
    tools = CLAUDE_TOOLS[fields["access"]]
    if tools:
        lines.append(f"tools: {tools}")
    lines += ["---", "",
              f"<!-- Generated by GADS from {rewrite_refs('`' + src_rel + '`')}. "
              "Edit the canonical role in the GADS kit, then upgrade. -->", "", rewrite_refs(body)]
    return "\n".join(lines)


def plan():
    """Map every kit-managed target path to the bytes the installer writes."""
    files = {}
    for rel in ROOT_FILES:
        text = rewrite_refs((SOURCE / rel).read_text(encoding="utf-8"))
        if rel == "CLAUDE.md":
            text = text.replace("\n@AGENTS.md\n", "\n@AGENTS.md\n@gads/PROJECT.md\n", 1)
        files[rel] = text.encode()
    for src_dir, dst_dir in KIT_DIRS.items():
        for f in sorted((SOURCE / src_dir).rglob("*")):
            if f.is_file():
                data = f.read_bytes()
                if f.suffix == ".md":
                    data = rewrite_refs(data.decode("utf-8")).encode()
                files[f"{dst_dir}/{f.relative_to(SOURCE / src_dir).as_posix()}"] = data
    for f in sorted((SOURCE / "agents").glob("*.md")):
        rel = f.relative_to(SOURCE).as_posix()
        files[f".claude/agents/gads-{f.stem}.md"] = claude_agent(rel, f.read_text(encoding="utf-8")).encode()
    files[".claude/settings.json"] = (SOURCE / CLAUDE_ADAPTER / "settings.json").read_bytes()
    files["gads/hooks/guard_bash.py"] = (SOURCE / CLAUDE_ADAPTER / "hooks/guard_bash.py").read_bytes()
    return files


def seeds():
    return {dst: (SOURCE / src).read_bytes() for src, dst in SEEDS.items()}


def read_lock(target):
    path = target / LOCK
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def write_lock(target, files):
    path = target / LOCK
    path.parent.mkdir(parents=True, exist_ok=True)
    lock = {"version": version(), "files": dict(sorted(files.items())), "seeds": sorted(SEEDS.values())}
    path.write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8", newline="\n")


def current_hash(path):
    return sha256(path.read_bytes()) if path.is_file() else None


def prune_empty_dirs(target, rel):
    """Remove empty parent directories of rel, stopping at the target root."""
    parent = (target / rel).parent
    while parent != target and parent.is_dir() and not any(parent.iterdir()):
        parent.rmdir()
        parent = parent.parent
